export function translateSiteText(value: string, language: SiteLanguage) {
  if (language === "pt") return value;
  const normalized = value.replace(/\s+/g, " ").trim();
  if (!normalized) return value;
  const exact = siteTranslations[normalized]?.[language];
  let translated = exact;

  if (!translated) {
    const productCount = normalized.match(/^(\d+) produtos?$/);
    if (productCount) translated = language === "en"
      ? `${productCount[1]} ${productCount[1] === "1" ? "product" : "products"}`
      : `${productCount[1]} ${productCount[1] === "1" ? "producto" : "productos"}`;
  }
  if (!translated) {
    const cartCount = normalized.match(/^Carrinho(?: com)? (\d+) itens?$/);
    if (cartCount) translated = language === "en"
      ? `Cart with ${cartCount[1]} ${cartCount[1] === "1" ? "item" : "items"}`
      : `Carrito con ${cartCount[1]} ${cartCount[1] === "1" ? "artículo" : "artículos"}`;
  }
  if (!translated && normalized.startsWith("Remover ")) {
    translated = `${language === "en" ? "Remove" : "Quitar"} ${translateSiteText(normalized.slice(8), language)}`;
  }
  if (!translated && normalized.startsWith("Ver ")) {
    translated = `${language === "en" ? "View" : "Ver"} ${translateSiteText(normalized.slice(4), language)}`;
  }
  if (!translated) {
    const productPrefixes: Array<[string, string, string]> = [
      ["Camisa ", "T-shirt ", "Camiseta "],
      ["Boné ", "Cap ", "Gorra "],
      ["Moletom ", "Sweatshirt ", "Sudadera "],
      ["Moleton ", "Sweatshirt ", "Sudadera "],
      ["Livro ", "Book ", "Libro "],
    ];
    const prefix = productPrefixes.find(([source]) => normalized.startsWith(source));
    if (prefix) translated = `${language === "en" ? prefix[1] : prefix[2]}${normalized.slice(prefix[0].length)}`;
  }
  if (!translated) return value;

  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}
